import streamlit as st
import ollama

st.title("Ollama Chat App")

user_prompt = st.text_area(
    "Ask a question:",
    "Explain byte pair encoding in one simple paragraph."
)

if st.button("Generate"):
    response = ollama.generate(
        model="llama3.2",
        prompt=user_prompt
    )

    st.write(response["response"])

