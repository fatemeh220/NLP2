import gradio as gr
import ollama

def chat_with_model(prompt):
    response = ollama.generate(
        model="llama3.2",
        prompt=prompt
    )
    return response["response"]

demo = gr.Interface(
    fn=chat_with_model,
    inputs="text",
    outputs="text",
    title="Ollama Gradio App",
    flagging_dir=r"C:\Users\Aurora\Desktop\NLP2\flagged_outputs"
)

demo.launch()

